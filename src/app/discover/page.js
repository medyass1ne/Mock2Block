"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { motion, AnimatePresence } from "framer-motion";
import Skeleton, { SkeletonTheme } from "react-loading-skeleton";
import DotField from "../../components/DotField";
import { Download, Eye, X } from "lucide-react";
import { Prism as SyntaxHighlighter } from 'react-syntax-highlighter';
import { vscDarkPlus } from 'react-syntax-highlighter/dist/cjs/styles/prism';

const CATEGORIES = ["All", "E-Commerce", "Social", "Fintech", "Utility"];

export default function Discover() {
  const router = useRouter();
  const [presets, setPresets] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [activeCategory, setActiveCategory] = useState("All");
  const [previewPreset, setPreviewPreset] = useState(null);
  
  useEffect(() => {
    const fetchPresets = async () => {
      try {
        const res = await fetch('/api/presets');
        if (!res.ok) throw new Error('Failed to fetch presets');
        const data = await res.json();
        const loadedPresets = data.presets || [];
        // Attach random clone counts for social proof
        const enrichedPresets = loadedPresets.map(p => ({
          ...p,
          cloneCount: Math.floor(Math.random() * 451) + 50,
          category: CATEGORIES[Math.floor(Math.random() * (CATEGORIES.length - 1)) + 1] // Random category for demo
        }));
        setPresets(enrichedPresets);
      } catch (err) {
        console.error(err);
        setError("Failed to load community presets.");
      } finally {
        setLoading(false);
      }
    };
    fetchPresets();
  }, []);

  const handleUsePreset = (presetId) => {
    router.push(`/?preset=${presetId}`);
  };

  return (
    <div className="relative min-h-screen text-white font-sans selection:bg-zinc-800 overflow-hidden bg-transparent">
      {/* <div className="absolute inset-0 z-0">
        <DotField
          dotRadius={1.5}
          dotSpacing={14}
          bulgeStrength={67}
          glowRadius={160}
          sparkle={true}
          waveAmplitude={0}
        />
      </div> */}
      
      <div className="relative z-10 p-4 sm:p-8 md:p-12">
        <div className="max-w-[1400px] mx-auto space-y-12">
        <header className="flex flex-col md:flex-row md:items-end justify-between gap-6">
          <div className="space-y-4">
            <h1 className="text-4xl md:text-5xl font-extrabold tracking-tight text-zinc-100">
              Discover Presets
            </h1>
            <p className="text-zinc-400 text-lg max-w-2xl leading-relaxed">
              Browse API schemas generated by the community. Click to instantly load them into your Builder.
            </p>
          </div>
        </header>

        <div className="flex overflow-x-auto pb-2 gap-3 scrollbar-hide">
          {CATEGORIES.map(cat => (
            <button
              key={cat}
              onClick={() => setActiveCategory(cat)}
              className={`rounded-full px-4 py-1.5 text-sm border whitespace-nowrap transition-colors ${
                activeCategory === cat 
                  ? "bg-white text-black border-white" 
                  : "border-zinc-700 text-zinc-400 hover:text-zinc-100 hover:bg-zinc-800"
              }`}
            >
              {cat}
            </button>
          ))}
        </div>

        <main>
          {loading ? (
            <SkeletonTheme baseColor="#18181b" highlightColor="#27272a">
              <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
                {[...Array(6)].map((_, i) => (
                  <div key={i} className="bg-zinc-900/50 border border-zinc-800 rounded-3xl p-6 h-[220px] flex flex-col justify-between">
                    <div>
                      <div className="flex justify-between items-start mb-4">
                        <Skeleton width={150} height={24} />
                        <Skeleton width={80} height={24} />
                      </div>
                      <Skeleton count={2} className="mb-4" />
                    </div>
                    <Skeleton height={45} borderRadius={12} />
                  </div>
                ))}
              </div>
            </SkeletonTheme>
          ) : error ? (
            <div className="bg-red-500/10 border border-red-500/20 text-red-400 p-6 rounded-2xl text-center">
              {error}
            </div>
          ) : presets.length === 0 ? (
            <div className="bg-zinc-900/50 border border-zinc-800 p-12 rounded-3xl text-center">
              <h3 className="text-xl font-semibold text-zinc-300 mb-2">No presets found</h3>
              <p className="text-zinc-500">Be the first to publish an API preset!</p>
            </div>
          ) : (
            <motion.div 
              className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6"
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              transition={{ duration: 0.5 }}
            >
              <AnimatePresence>
                {presets
                  .filter(p => activeCategory === "All" || p.category === activeCategory)
                  .map((preset, idx) => (
                  <motion.div
                    key={preset.presetId}
                    initial={{ opacity: 0, y: 20 }}
                    animate={{ opacity: 1, y: 0 }}
                    transition={{ duration: 0.4, delay: idx * 0.05 }}
                    className="group bg-zinc-900/50 border border-zinc-800 shadow-sm rounded-3xl p-6 relative overflow-hidden hover:bg-zinc-800/50 transition-all flex flex-col h-full"
                  >
                    <div className="flex-1 space-y-4 relative z-10">
                      <div className="flex justify-between items-start gap-4">
                        <h3 className="text-xl font-bold text-white line-clamp-1">{preset.title}</h3>
                        <span className="px-2.5 py-1 bg-zinc-950 text-zinc-400 text-xs rounded-md border border-zinc-800 whitespace-nowrap">
                          {preset.resources?.length || 0} endpoints
                        </span>
                      </div>
                      
                      <p className="text-sm text-zinc-400 line-clamp-3">
                        {preset.description || "No description provided."}
                      </p>
                      
                      <div className="flex items-center gap-2 mt-4 pt-4 border-t border-zinc-800">
                        <div className="w-6 h-6 rounded-full bg-zinc-800 border border-zinc-700 flex items-center justify-center text-[10px] font-bold text-white shadow-sm">
                          {preset.author?.[0]?.toUpperCase() || '?'}
                        </div>
                        <span className="text-xs text-zinc-300 font-medium">{preset.author}</span>
                        <div className="ml-auto flex items-center gap-3">
                          <span className="text-xs text-zinc-500 flex items-center gap-1">
                            <Download className="w-3 h-3" /> {preset.cloneCount}
                          </span>
                          <span className="text-xs text-zinc-500">
                            {new Date(preset.createdAt).toLocaleDateString()}
                          </span>
                        </div>
                      </div>
                    </div>
                    
                    <div className="mt-6 flex gap-2 relative z-10">
                      <button 
                        onClick={() => setPreviewPreset(preset)}
                        className="flex-1 flex items-center justify-center gap-2 py-3 bg-zinc-800 text-white hover:bg-zinc-700 text-sm font-semibold rounded-xl transition-colors shadow-sm"
                      >
                        <Eye className="w-4 h-4" />
                        Preview
                      </button>
                      <button 
                        onClick={() => handleUsePreset(preset.presetId)}
                        className="flex-1 flex items-center justify-center gap-2 py-3 bg-white text-black hover:bg-zinc-200 text-sm font-semibold rounded-xl transition-colors shadow-sm"
                      >
                        <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M13 10V3L4 14h7v7l9-11h-7z" />
                        </svg>
                        Use
                      </button>
                    </div>
                  </motion.div>
                ))}
              </AnimatePresence>
            </motion.div>
          )}
        </main>
      </div>
      
      {/* Preview Modal */}
      <AnimatePresence>
        {previewPreset && (
          <div className="fixed inset-0 z-[200] flex items-center justify-center p-4 bg-black/80 backdrop-blur-xl">
            <motion.div 
              initial={{ opacity: 0, scale: 0.95 }}
              animate={{ opacity: 1, scale: 1 }}
              exit={{ opacity: 0, scale: 0.95 }}
              className="bg-zinc-950 border border-zinc-800 rounded-3xl w-full max-w-2xl max-h-[85vh] flex flex-col shadow-2xl relative overflow-hidden"
            >
              <div className="flex justify-between items-center p-6 border-b border-zinc-800/50">
                <div>
                  <h3 className="text-xl font-bold text-white">{previewPreset.title}</h3>
                  <p className="text-zinc-500 text-sm mt-1">{previewPreset.resources?.length} Resources</p>
                </div>
                <button onClick={() => setPreviewPreset(null)} className="text-zinc-500 hover:text-white transition-colors p-2 bg-zinc-900 rounded-full hover:bg-zinc-800">
                  <X className="w-5 h-5" />
                </button>
              </div>
              <div className="p-6 overflow-y-auto flex-1 custom-scrollbar bg-zinc-950">
                <SyntaxHighlighter 
                  language="json" 
                  style={vscDarkPlus} 
                  customStyle={{ background: 'transparent', margin: 0, padding: 0 }}
                  wrapLines={true}
                >
                  {JSON.stringify(previewPreset.resources, null, 2)}
                </SyntaxHighlighter>
              </div>
              <div className="p-6 border-t border-zinc-800/50 bg-zinc-900/50 flex justify-end">
                <button 
                  onClick={() => {
                    handleUsePreset(previewPreset.presetId);
                    setPreviewPreset(null);
                  }}
                  className="px-6 py-2.5 bg-white text-black hover:bg-zinc-200 text-sm font-semibold rounded-xl transition-colors shadow-sm flex items-center gap-2"
                >
                  <Download className="w-4 h-4" /> Load Preset
                </button>
              </div>
            </motion.div>
          </div>
        )}
      </AnimatePresence>
      </div>
    </div>
  );
}
